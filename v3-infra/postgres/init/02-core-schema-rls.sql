CREATE INDEX IF NOT EXISTS idx_schools_dane_code ON schools(dane_code);
CREATE INDEX IF NOT EXISTS idx_schools_active ON schools(is_active) WHERE is_active = TRUE;

CREATE TABLE IF NOT EXISTS campuses (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    school_id BIGINT NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
    dane_code VARCHAR(30),
    name VARCHAR(180) NOT NULL,
    address VARCHAR(200),
    phones VARCHAR(80),
    zone_type VARCHAR(20) NOT NULL DEFAULT 'URBAN',
    is_main BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_campuses_school ON campuses(school_id);

CREATE TABLE IF NOT EXISTS school_shifts (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    school_id BIGINT NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
    code SMALLINT NOT NULL,
    name VARCHAR(80) NOT NULL,
