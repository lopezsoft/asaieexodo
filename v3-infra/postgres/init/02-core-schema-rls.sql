-- -----------------------------------------------------------------------------
-- MODULO 1: CATALOGOS GLOBALES Y GEOGRAFIA (Compartidos)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS countries (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iso_code VARCHAR(5) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    phone_prefix VARCHAR(10),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS departments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id INTEGER NOT NULL REFERENCES countries(id),
    dane_code VARCHAR(10) NOT NULL,
    name VARCHAR(120) NOT NULL,
    UNIQUE (country_id, dane_code)
);

CREATE TABLE IF NOT EXISTS cities (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id INTEGER NOT NULL REFERENCES departments(id),
    dane_code VARCHAR(15) NOT NULL,
    name VARCHAR(120) NOT NULL,
    UNIQUE (department_id, dane_code)
);

CREATE TABLE IF NOT EXISTS document_types (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(10) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    applies_to_student BOOLEAN NOT NULL DEFAULT TRUE,
    applies_to_adult BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS health_providers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) UNIQUE,
    name VARCHAR(150) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ethnic_groups (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) UNIQUE,
    name VARCHAR(120) NOT NULL
);

CREATE TABLE IF NOT EXISTS disability_types (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(40) NOT NULL DEFAULT 'DISABILITY', -- DISABILITY, EXCEPTIONAL_CAPACITY, CONFLICT_VICTIM
    code VARCHAR(20),
    name VARCHAR(150) NOT NULL
);

