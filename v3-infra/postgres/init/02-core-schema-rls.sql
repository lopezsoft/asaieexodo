CREATE TABLE IF NOT EXISTS schools (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    public_uuid UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    country_id INTEGER NOT NULL DEFAULT 1 REFERENCES countries(id),
    city_id INTEGER REFERENCES cities(id),
    dane_code VARCHAR(30) UNIQUE,
    tax_id VARCHAR(30),
    name VARCHAR(250) NOT NULL,
    short_name VARCHAR(80),
    resolution_text TEXT,
    header_line_1 VARCHAR(250),
    header_line_2 VARCHAR(250),
    footer_text TEXT,
    director_name VARCHAR(150),
    director_document VARCHAR(40),
    director_signature_url TEXT,
    secretary_name VARCHAR(150),
    secretary_document VARCHAR(40),
    secretary_signature_url TEXT,
    address VARCHAR(200),
    phones VARCHAR(100),
    email VARCHAR(150),
    website VARCHAR(150),
    logo_url TEXT,
    shield_url TEXT,
    storage_folder VARCHAR(120) NOT NULL,
    subscription_lock_date DATE NOT NULL DEFAULT (CURRENT_DATE + INTERVAL '1 year'),
    settings JSONB NOT NULL DEFAULT '{}'::jsonb,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    legacy_db_name VARCHAR(60) UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
