-- -----------------------------------------------------------------------------
-- POLITICAS ROW-LEVEL SECURITY (RLS) PARA AISLAMIENTO MULTI-TENANT ESTRICTO
-- -----------------------------------------------------------------------------
DO $$
DECLARE
    tenant_table TEXT;
    tenant_tables TEXT[] := ARRAY[
        'campuses',
        'school_shifts',
        'academic_years',
        'academic_periods',
        'user_school_memberships',
        'student_profiles',
        'teacher_profiles',
        'family_profiles',
        'student_family_links',
        'education_levels',
        'grades',
        'academic_areas',
        'subjects',
        'grading_scales',
        'academic_groups',
        'course_assignments',
        'student_enrollments',
        'academic_grades',
        'observer_templates',
        'student_observers',
        'observer_annotations'
    ];
BEGIN
    FOREACH tenant_table IN ARRAY tenant_tables LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY;', tenant_table);
        EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY;', tenant_table);
        EXECUTE format('DROP POLICY IF EXISTS tenant_isolation_policy ON %I;', tenant_table);
        EXECUTE format(
            'CREATE POLICY tenant_isolation_policy ON %I
             USING (is_tenant_bypass_enabled() OR school_id = current_tenant_school_id())
             WITH CHECK (is_tenant_bypass_enabled() OR school_id = current_tenant_school_id());',
            tenant_table
        );
    END LOOP;
END$$;

-- -----------------------------------------------------------------------------
-- VISTA DE COMPATIBILIDAD PARA SUBREPORTES DE JASPERREPORTS (encabezado_reportes)
-- Permite que report_header_school.jrxml funcione en PostgreSQL sin redisenar
-- -----------------------------------------------------------------------------
CREATE OR REPLACE VIEW encabezado_reportes AS
SELECT
    s.id AS id,
    s.id AS school_id,
    s.name AS nombre,
    s.dane_code AS cod_dane,
    s.tax_id AS nit,
    COALESCE(s.header_line_1, s.name) AS encabezado1,
    COALESCE(s.header_line_2, s.resolution_text, '') AS encabezado2,
    COALESCE(s.footer_text, s.address, '') AS pie,
    s.logo_url AS logo,
    s.shield_url AS escudo
FROM schools s
WHERE is_tenant_bypass_enabled() OR s.id = current_tenant_school_id();

